package chapter2;

public class ImplicitConversion1 {
    public static void main(String[] args) {
        float val1 = 3;
        long val2 = 5;
        double val3 = 7;
        byte val4 = 9;
        short val5 = 11;

        System.out.println(val1);
        System.out.println(val2);
        System.out.println(val3);
        System.out.println(val4);
        System.out.println(val5);


    }
}
