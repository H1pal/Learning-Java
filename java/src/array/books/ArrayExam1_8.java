package array.books;

public class ArrayExam1_8 {
    public static void main(String[] args) {
        int[] arr = {10, 20, 30, 40, 50};
        for (int index : arr) {
            System.out.println(index + "\t");
        }
        System.out.println();
        char[] arr_ch = {'A', 'B', 'C'};
        for (int index : arr_ch) {
            System.out.println((char)index+"\t");
        }
    }
}
